import fs from 'node:fs';
import path from 'node:path';
import {spawn} from 'node:child_process';
import assert from 'node:assert/strict';
const root=path.resolve('dist/installer-smoke',String(Date.now()));
const target=path.join(root,'Link Garden'),home=path.join(root,'home');
const appData=path.join(home,'AppData/Roaming'),local=path.join(home,'AppData/Local');
fs.mkdirSync(local,{recursive:true});
const old=path.join(appData,'Link Garden/vault');fs.mkdirSync(old,{recursive:true});
fs.writeFileSync(path.join(old,'legacy.md'),'# legacy migration fixture');
const env={...process.env,APPDATA:appData,LOCALAPPDATA:local,USERPROFILE:home,CODEX_HOME:path.join(home,'.codex')};
delete env.LINK_GARDEN_DATA_DIR;delete env.LINK_GARDEN_VAULT;delete env.ELECTRON_RUN_AS_NODE;
async function run(exe,args){const proc=spawn(exe,args,{env,windowsHide:true,stdio:'ignore'});const timer=setTimeout(()=>proc.kill(),60000);const code=await new Promise((resolve,reject)=>{proc.once('error',reject);proc.once('exit',resolve);});clearTimeout(timer);assert.equal(code,0,exe);}
const installer=path.resolve('dist/installer-test/Link-Garden-Setup-0.5.0.exe');
await run(installer,['/S',`/D=${target}`]);
assert.ok(fs.existsSync(path.join(target,'Link Garden.exe')));
assert.ok(fs.existsSync(path.join(target,'data/vault/legacy.md')));
assert.ok(fs.existsSync(path.join(target,'data/integrations/REGISTER-MCP.md')));
assert.ok(fs.existsSync(path.join(old,'legacy.md')));
assert.ok(!fs.existsSync(path.join(local,'link-garden-updater/installer.exe')));
fs.writeFileSync(path.join(target,'data/vault/retained.md'),'# retain my note');
fs.writeFileSync(path.join(target,'keep-user.txt'),'user-owned root file');
await run(installer,['/S',`/D=${target}`]);
assert.equal(fs.readFileSync(path.join(target,'data/vault/retained.md'),'utf8'),'# retain my note');
await run(path.join(target,'Uninstall Link Garden.exe'),['/S']);
for(let i=0;i<120&&fs.existsSync(path.join(target,'Link Garden.exe'));i++)await new Promise(r=>setTimeout(r,500));
assert.ok(!fs.existsSync(path.join(target,'resources/app.asar')));
assert.ok(!fs.existsSync(path.join(target,'Link Garden.exe')));
assert.equal(fs.readFileSync(path.join(target,'data/vault/retained.md'),'utf8'),'# retain my note');
assert.equal(fs.readFileSync(path.join(target,'keep-user.txt'),'utf8'),'user-owned root file');
console.log('PASS: actual installer, legacy migration, reinstall and uninstall preserve local data; no AppData installer cache. Fixture: '+root);
